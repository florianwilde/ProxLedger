/** Report-Historie (gekürzt) für die Host-Detailansicht. */
export const reports: Report[] = hosts.flatMap((host) =>
  Array.from({ length: 6 }, (_, i) => {
    const zeitpunkt = new Date(
      new Date(host.letzterReport ?? HEUTE).getTime() - i * 24 * 60 * 60 * 1000,
    ).toISOString();
    return {
      id: `${host.id}-r${i}`,
      hostId: host.id,
      zeitpunkt,
      status: host.subscription.status,
      key: host.subscription.key,
      nextduedate: host.subscription.nextduedate,
      agentVersion: host.agentVersion,
      paketUpdates: host.paketUpdates === null ? null : Math.max(0, host.paketUpdates - i),
    };
  }),
);
